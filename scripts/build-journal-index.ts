/**
 * Emits `src/data/journal.generated.ts` — a browser-safe summary of every
 * journal post (no body) so the client-side search index and any "latest
 * articles" rails can include the journal without touching `fs`.
 *
 * Run: npm run content:journal   (also part of `npm run build` via prebuild)
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { getAllPosts } from '../src/lib/journal/index';

const posts = getAllPosts();
const docs = posts.map((p) => ({
  slug: p.slug,
  title: p.title,
  excerpt: p.excerpt,
  date: p.date,
  category: p.category,
  tags: p.tags,
  image: p.image,
  author: p.author,
  readingMinutes: p.readingMinutes,
  featured: p.featured ?? false,
}));

const out = `// AUTO-GENERATED by scripts/build-journal-index.ts — do not edit.
// Source: content/journal/*.mdx (${docs.length} posts)

export interface JournalDoc {
  slug: string;
  title: string;
  excerpt: string;
  date: string;
  category: string;
  tags: string[];
  image: string;
  author: string;
  readingMinutes: number;
  featured: boolean;
}

export const JOURNAL_DOCS: JournalDoc[] = ${JSON.stringify(docs, null, 2)};
`;

const dest = join(process.cwd(), 'src', 'data', 'journal.generated.ts');
writeFileSync(dest, out);
console.log(`✔ ${docs.length} journal docs → src/data/journal.generated.ts`);
