export const STYLE_KEYS = Object.keys(P);

export function paletteFor(style: string, seed: string): Palette {
  const base = P[style] ?? P['contemporary']!;
  const r = rng(`${seed}:pal`);
  // small deterministic variation per image so galleries don't look cloned
  const jitter = (h: string, dl: number) => shadeHex(h, r.jitter(dl));
  return {
    ...base,
    wall: jitter(base.wall, 0.02),
    accent: jitter(base.accent, 0.04),
    floor: jitter(base.floor, 0.02),
    fabric: jitter(base.fabric, 0.03),
  };
}

