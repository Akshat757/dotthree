import type { BeforeAfterPair, Bhk, BudgetBand, ImageRef, Project, PropertyType, SurfaceType } from '@/types/content';

import { img } from './images';

interface Row {
  slug: string;
  title: string;
  locality: string;
  city?: string;
  type: PropertyType;
  bhk?: Bhk;
  sqft?: number;
  nature: 'NEW' | 'RENOVATION';
  styles: string[];
  rooms: string[];
  budget: number;
  weeks: number;
  completed: string;
  vastu?: boolean;
  compact?: boolean;
  joint?: boolean;
  featured?: boolean;
  brief: string;
  challenge: string;
  solution: string;
  note?: string;
  materials: string[];
  designers: string[];
  palette?: Partial<Record<SurfaceType, string>>;
  template?: string;
  /** number of gallery images (default 6) and which have before shots */
  gallery?: number;
  befores?: number[];
  baModes?: BeforeAfterPair['mode'][];
}

export function budgetBandOf(inr: number): BudgetBand {
  if (inr < 300_000) return 'UNDER_3L';
  if (inr < 700_000) return 'L3_7';
  if (inr < 1_500_000) return 'L7_15';
  if (inr < 3_000_000) return 'L15_30';
  return 'ABOVE_30L';
}

