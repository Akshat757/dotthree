function p(r: Row, orderIndex: number): Project {
  const galleryCount = r.gallery ?? 6;
  const images: ImageRef[] = Array.from({ length: galleryCount }, (_, i) => {
    const ref = img(`proj-${r.slug}-${String(i + 1).padStart(2, '0')}`);
    return { ...ref, roomType: r.rooms[i % r.rooms.length], styleBucket: r.styles[0] };
  });
  const befores = r.befores ?? (r.nature === 'RENOVATION' ? [1, 2] : [1]);
  const modes = r.baModes ?? (r.nature === 'RENOVATION' ? ['before-after', 'before-after'] : ['render-vs-built']);
  const beforeAfters: BeforeAfterPair[] = befores.map((n, i) => {
    const after = images[n - 1] ?? images[0]!;
    return {
      id: `${r.slug}-ba-${n}`,
      before: img(`proj-${r.slug}-${String(n).padStart(2, '0')}-before`),
      after,
      label: ROOM_LABELS[after.roomType ?? ''] ?? after.roomType,
      mode: modes[i] ?? 'before-after',
    };
  });
  return {
    slug: r.slug,
    title: r.title,
    city: r.city ?? 'Indore',
    locality: r.locality,
    propertyType: r.type,
    bhk: r.bhk,
    carpetAreaSqft: r.sqft,
    segment: ['OFFICE', 'CLINIC', 'RETAIL', 'RESTAURANT'].includes(r.type) ? 'COMMERCIAL' : 'RESIDENTIAL',
    nature: r.nature,
    styles: r.styles,
    roomTypes: r.rooms,
    budgetBand: budgetBandOf(r.budget),
    budgetInr: r.budget,
    durationWeeks: r.weeks,
    completedOn: r.completed,
    vastuAligned: r.vastu ?? false,
    compactHome: r.compact,
    jointFamily: r.joint,
    featured: r.featured ?? false,
    orderIndex,
    brief: r.brief,
    challenge: r.challenge,
    solution: r.solution,
    designerNote: r.note,
    heroImage: { ...images[0]!, id: `proj-${r.slug}-hero` },
    images,
    beforeAfters,
    materialSlugs: r.materials,
    designerSlugs: r.designers,
    testimonialId: undefined,
    palette: r.palette,
    roomTemplateSlug: r.template,
  };
}

